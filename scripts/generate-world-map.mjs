import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const [source, destination] = process.argv.slice(2);
if (!source || !destination) {
  throw new Error("usage: node scripts/generate-world-map.mjs <Natural Earth .shp> <output.svg>");
}

const buffer = readFileSync(resolve(source));
const project = (longitude, latitude) => ({
  x: 24 + ((longitude + 180) / 360) * 712,
  y: 32 + ((85 - latitude) / 145) * 356,
});
const compact = (value) => Number(value.toFixed(1));
const paths = [];

for (let offset = 100; offset + 8 <= buffer.length;) {
  const contentLength = buffer.readInt32BE(offset + 4) * 2;
  const start = offset + 8;
  const shapeType = buffer.readInt32LE(start);
  if (shapeType === 5 && contentLength >= 44) {
    const partCount = buffer.readInt32LE(start + 36);
    const pointCount = buffer.readInt32LE(start + 40);
    const partsOffset = start + 44;
    const pointsOffset = partsOffset + partCount * 4;
    const parts = Array.from({ length: partCount }, (_, index) => buffer.readInt32LE(partsOffset + index * 4));
    parts.push(pointCount);
    const commands = [];
    for (let part = 0; part < partCount; part += 1) {
      const points = [];
      for (let index = parts[part]; index < parts[part + 1]; index += 1) {
        const longitude = buffer.readDoubleLE(pointsOffset + index * 16);
        const latitude = buffer.readDoubleLE(pointsOffset + index * 16 + 8);
        points.push({ longitude, latitude });
      }
      if (!points.length || Math.max(...points.map(({ latitude }) => latitude)) < -60) continue;
      points.forEach(({ longitude, latitude }, index) => {
        const { x, y } = project(longitude, Math.max(-60, Math.min(85, latitude)));
        commands.push(`${index ? "L" : "M"}${compact(x)} ${compact(y)}`);
      });
      commands.push("Z");
    }
    if (commands.length) paths.push(`<path d="${commands.join(" ")}"/>`);
  }
  offset = start + contentLength;
}

const svg = `<!-- Natural Earth 1:110m Admin 0 Countries v5.1.1, public domain. Generated by scripts/generate-world-map.mjs. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 760 420" role="presentation">
  <defs>
    <linearGradient id="world-fill" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#253640" stop-opacity=".82"/>
      <stop offset=".48" stop-color="#16242b" stop-opacity=".74"/>
      <stop offset="1" stop-color="#0b1419" stop-opacity=".92"/>
    </linearGradient>
    <filter id="world-shadow" x="-8%" y="-12%" width="116%" height="132%">
      <feDropShadow dx="0" dy="8" stdDeviation="9" flood-color="#00070b" flood-opacity=".64"/>
      <feDropShadow dx="0" dy="0" stdDeviation="1.5" flood-color="#bfeef4" flood-opacity=".13"/>
    </filter>
  </defs>
  <g fill="url(#world-fill)" stroke="rgba(177,211,219,.28)" stroke-width=".62" stroke-linejoin="round" vector-effect="non-scaling-stroke" filter="url(#world-shadow)">
    ${paths.join("\n    ")}
  </g>
</svg>
`;

writeFileSync(resolve(destination), svg);
